// Mock-mode end-to-end run: node scripts/e2e.mjs  (dev server must be running on :8080)
import { chromium } from "playwright";
import fs from "fs";
const BASE = process.env.BASE_URL ?? "http://localhost:8080";
const OUT = "screenshots";
fs.mkdirSync(OUT, { recursive: true });
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 430, height: 900 }, deviceScaleFactor: 2, acceptDownloads: true });
const page = await ctx.newPage();
const errors = [];
page.on("pageerror", (e) => errors.push(e.message));
const shot = (n) => page.screenshot({ path: `${OUT}/${n}.png`, fullPage: true });
const next = () => page.getByTestId("next").click();

await page.goto(BASE); await page.waitForLoadState("networkidle"); await shot("01-landing");
await page.getByText("Create Their Adventure →").click();
await next(); await page.getByTestId("error").waitFor(); await shot("02a-wizard-validation");
await page.getByTestId("name").fill("Poppy"); await page.getByText("She/her").click(); await shot("02-wizard-hero");
