const edited = await page.getByTestId("page-text").textContent();
const dl = page.waitForEvent("download");
await page.getByTestId("export").click();
const d = await dl; await d.saveAs("sample-book-mock.pdf");
const refLog = await page.evaluate(() => window.__inktalesRefLog);
const pageCalls = refLog.filter((r) => r.index >= 0);
const refOk = refLog[0]?.index === -1 && pageCalls.length > 0 && pageCalls.every((r) => r.usedCover);
console.log(JSON.stringify({ edited, refOk, coverFirst: refLog[0], pageImageCalls: pageCalls.length, allPagesUsedCoverRef: pageCalls.every((r) => r.usedCover), pdf: "sample-book-mock.pdf", errors }, null, 2));
