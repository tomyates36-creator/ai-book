await next(); await page.getByTestId("interest-Dinosaurs").click(); await page.getByTestId("interest-Drawing").click();
await page.getByTestId("pet").fill("Biscuit"); await page.getByTestId("town").fill("Manchester"); await shot("04-wizard-loves");
await next(); await page.getByTestId("theme-space").click(); await page.getByText("Kindness").click(); await shot("05-wizard-story");
await next(); await page.getByTestId("style-crayon").click(); await shot("06-wizard-style");
await next(); await page.getByTestId("dedication").fill("Nasty knife"); await next(); await page.getByTestId("error").waitFor(); await shot("07a-safety-filter");
await page.getByTestId("dedication").fill("For Poppy, our little star. Keep exploring!"); await page.getByTestId("from").fill("Grandma & Grandad"); await shot("07-wizard-dedication");
await next();
await page.getByTestId("title").waitFor(); await page.getByTestId("status").waitFor({ state: "detached", timeout: 20000 }); await shot("08-preview-watermarked");
await page.getByTestId("buy-print").click(); await page.getByTestId("shopify-placeholder").waitFor(); await shot("09-checkout-placeholder");
await page.getByTestId("simulate-paid").click();
await page.getByTestId("book-title").waitFor(); await page.getByTestId("busy").waitFor({ state: "detached", timeout: 30000 }); await shot("10-viewer-cover");
await page.getByTestId("next-page").click(); await page.waitForTimeout(500); await shot("11-viewer-dedication");
